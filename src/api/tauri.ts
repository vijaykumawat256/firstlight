import { invoke } from "@tauri-apps/api/core";
import { listen } from "@tauri-apps/api/event";
import { openUrl } from "@tauri-apps/plugin-opener";
import { assertHttps, type Backend } from "./backend";
import type { AccountView, AiProvider, AiStatus, AppInfo, AppSettings, Briefing, CalendarInfo, CalEvent, MailResult, OAuthAvailability, OpenTarget, SyncSummary, SystemStatus, UpdateStatus } from "./types";

export const tauriBackend: Backend = {
  getEvents: (start, end) => invoke<CalEvent[]>("get_events", { start, end }),
  getBriefing: () => invoke<Briefing>("get_briefing"),
  dismissUpNext: () => invoke<void>("dismiss_up_next"),
  openBriefing: () => invoke<void>("open_briefing"),
  onUpNextShown: async (callback) => listen("up-next-shown", () => callback()),
  getMailDigest: (force) => invoke<MailResult>("get_mail_digest", { force }),
  enableAppleMail: () => invoke<AppSettings>("enable_apple_mail"),
  enableAccountMail: (accountId) => invoke<AppSettings>("enable_account_mail", { accountId }),
  createEvent: (event, calendarId) => invoke("create_event", { event, calendarId: calendarId ?? null }),
  writableCalendars: () => invoke("writable_calendars"),
  getOwnEvent: (id) => invoke("get_own_event", { id }),
  exportOwnEvents: () => invoke("export_own_events"),
  skipOccurrence: (id) => invoke("skip_event_occurrence", { id }),
  getSystemAccent: () => invoke("get_system_accent"),
  prepareInvite: (id, recipients, openMail) => invoke("prepare_invite", { id, recipients, openMail }),
  inviteSenders: () => invoke("invite_senders"),
  invitePreview: (id) => invoke("invite_preview", { id }),
  sendInviteMail: (id, recipients, mailboxId) => invoke("send_invite_mail", { id, recipients, mailboxId }),
  updateEvent: (id, event) => invoke("update_event", { id, event }),
  deleteEvent: (id) => invoke("delete_event", { id }),
  addImapMailbox: (preset, address, password, host) => invoke<AppSettings>("add_imap_mailbox", { preset, address, password, host: host ?? null }),
  removeImapMailbox: (mailboxId) => invoke<AppSettings>("remove_imap_mailbox", { mailboxId }),
  openMailMessage: (target: OpenTarget) => invoke<void>("open_mail_message", { target }),
  aiStatus: () => invoke<AiStatus>("ai_status"),
  aiPreview: () => invoke<string>("ai_preview"),
  enableAi: (provider: AiProvider, key, confirm) => invoke<AppSettings>("enable_ai", { provider, key, confirm }),
  disableAi: () => invoke<AppSettings>("disable_ai"),
  forgetAiKey: () => invoke<AppSettings>("forget_ai_key"),
  aiKeys: () => invoke<AiProvider[]>("ai_keys"),
  signInOpenrouter: () => invoke("sign_in_openrouter"),
  getAiSummary: () => invoke<string | null>("get_ai_summary").catch(() => null),
  getAppInfo: () => invoke<AppInfo>("get_app_info"),
  checkForUpdate: () => invoke<UpdateStatus>("check_for_update"),
  installUpdate: () => invoke<void>("install_update"),
  onUpdateAvailable: async (callback) => listen<string>("update-available", (e) => callback(e.payload)),
  getLastCrashReport: () => invoke<string | null>("get_last_crash_report"),
  clearCrashReports: () => invoke<void>("clear_crash_reports"),
  getSettings: () => invoke<AppSettings>("get_settings"),
  setSettings: (settings) => invoke<AppSettings>("set_settings", { settings }),
  exportSettings: () => invoke<string>("export_settings"),
  saveSettingsExport: () => invoke<string>("save_settings_export"),
  importSettings: (text) => invoke<AppSettings>("import_settings", { text }),
  eraseAllData: () => invoke<void>("erase_all_data"),
  onSettingsChanged: async (callback) => listen("settings-changed", () => callback()),
  getCalendars: () => invoke<CalendarInfo[]>("get_calendars"),
  listAccounts: () => invoke<AccountView[]>("list_accounts"),
  addIcsAccount: (name, url) => invoke<AccountView>("add_ics_account", { name, url }),
  addCaldavAccount: (name, server, username, password) => invoke<AccountView>("add_caldav_account", { name, server, username, password }),
  oauthAvailable: () => invoke<OAuthAvailability>("oauth_available"),
  addOauthAccount: (provider) => invoke<AccountView>("add_oauth_account", { provider }),
  cancelOauth: () => invoke<void>("cancel_oauth"),
  systemCalendarStatus: () => invoke<SystemStatus>("system_calendar_status"),
  addSystemAccount: () => invoke<AccountView>("add_system_account"),
  openPrivacySettings: (pane) => invoke<void>("open_privacy_settings", { pane }),
  addDemoAccount: () => invoke<AccountView>("add_demo_account"),
  removeAccount: (id) => invoke<void>("remove_account", { id }),
  renameAccount: (id, name) => invoke<void>("rename_account", { id, name }),
  setCalendarVisible: (calendarId, visible) => invoke<void>("set_calendar_visible", { calendarId, visible }),
  setCalendarColour: (calendarId, colour) => invoke<void>("set_calendar_colour", { calendarId, colour }),
  refreshNow: () => invoke<void>("refresh_now"),
  onSyncFinished: async (callback) => listen<SyncSummary>("sync-finished", (e) => callback(e.payload)),
  getAutostart: () => invoke<boolean>("get_autostart"),
  setAutostart: (enabled) => invoke<void>("set_autostart", { enabled }),
  onUnlock: async (callback) => listen("system-unlock", () => callback()),
  openUrl: (url) => openUrl(assertHttps(url).toString()),
};
